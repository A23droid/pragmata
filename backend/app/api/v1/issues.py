router = APIRouter(prefix="/issues", tags=["Issues"])


def generate_issue_id() -> str:
    return f"PRAG-{secrets.token_hex(3).upper()}"


# Rooms created for every issue, in order. Resolution + Implementation rooms
# are created upfront so their IDs are persisted even though agents don't
# use them until later phases.
_ISSUE_ROOMS = [
    (ChannelType.INVESTIGATION, "Investigation"),
    (ChannelType.RESOLUTION, "Resolution"),
    (ChannelType.IMPLEMENTATION, "Implementation"),
]


async def _provision_switch_rooms(issue_id: str, db: AsyncSession) -> None:
    """
    Create all three Switch rooms for a new issue and persist their
    ConversationReference rows to the database.

    This is best-effort: Switch connectivity failures are logged but do not
    abort issue creation. Canonical state is always PostgreSQL.
    """
    for channel_type, label in _ISSUE_ROOMS:
        room_req = SwitchRoomCreate(
            issue_id=issue_id,
            room_name=f"PRAGMATA {label} — {issue_id}",
            channel_type=channel_type,
            topic=f"{label} channel for issue {issue_id}",
            initial_members=["pragmata-orchestrator"],
        )
        room_data = await switch_adapter.create_or_join_room(room_req)
        room_id: str = room_data["room_id"]

        # Persist the room reference regardless of whether Switch is online.
        # The room_id is deterministically generated by the adapter so it
        # remains stable across reconnects.
        ref = ConversationReference(
            issue_id=issue_id,
            room_id=room_id,
            channel_type=channel_type,
            metadata_json={
                "room_name": room_data.get("name", ""),
                "topic": room_data.get("topic", ""),
                "switch_active": room_data.get("active", False),
            },
        )
        db.add(ref)


@router.post("", response_model=IssueResponse, status_code=status.HTTP_201_CREATED)
async def create_issue(
    payload: IssueCreate,
    db: AsyncSession = Depends(get_db),
):
    """
    Intake bug report from any user (reporter/developer).
    Non-technical plain language input is accepted.
    Three Switch rooms (Investigation, Resolution, Implementation) are
    provisioned and their IDs persisted to the database.
    """
    # Resolve or create default project if not provided
    project_id = payload.project_id
    if not project_id:
        default_project = await get_or_create_default_project(db)
        project_id = default_project.id
    else:
        project = await db.get(Project, project_id)
        if not project:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Project with ID '{project_id}' does not exist.",
            )

    issue_id = generate_issue_id()

    # If the report is lacking basic detail mark NEEDS_INFORMATION, else RECEIVED.
    initial_status = IssueStatus.RECEIVED
    if len(payload.description.strip()) < 10:
        initial_status = IssueStatus.NEEDS_INFORMATION

    issue = Issue(
        id=issue_id,
        project_id=project_id,
        title=payload.title.strip(),
        description=payload.description.strip(),
        expected_behavior=payload.expected_behavior.strip() if payload.expected_behavior else None,
        steps_attempted=payload.steps_attempted.strip() if payload.steps_attempted else None,
        reporter_environment=payload.reporter_environment,
        status=initial_status,
    )
    db.add(issue)

    # Audit event for intake
    audit = AuditEvent(
        issue_id=issue_id,
        event_type="ISSUE_SUBMITTED",
        from_state=None,
        to_state=initial_status.value,
        actor="reporter",
        payload={
            "title": issue.title,
            "has_environment": bool(issue.reporter_environment),
        },
    )
    db.add(audit)

    # Provision Switch rooms and persist ConversationReference rows.
    # Must happen before commit so they share the same transaction.
    await _provision_switch_rooms(issue_id, db)

    await db.commit()
    await db.refresh(issue)
    return issue


@router.get("", response_model=List[IssueResponse])
async def list_issues(
    status_filter: Optional[IssueStatus] = Query(None, alias="status", description="Filter by issue status"),
    project_id: Optional[uuid.UUID] = Query(None, description="Filter by project ID"),
    db: AsyncSession = Depends(get_db),
):
    """List issues with optional status and project filters."""
    stmt = select(Issue).order_by(Issue.created_at.desc())
    if status_filter:
        stmt = stmt.where(Issue.status == status_filter)
    if project_id:
        stmt = stmt.where(Issue.project_id == project_id)

    result = await db.execute(stmt)
    return result.scalars().all()


@router.get("/{issue_id}", response_model=IssueDetailResponse)
async def get_issue(issue_id: str, db: AsyncSession = Depends(get_db)):
    """Fetch complete issue details including project metadata, approvals, audit trail, and Switch rooms."""
    stmt = (
        select(Issue)
        .where(Issue.id == issue_id)
        .options(
            selectinload(Issue.project),
            selectinload(Issue.approvals),
            selectinload(Issue.audit_events),
            selectinload(Issue.conversations),
            selectinload(Issue.solutions),
        )
    )
    result = await db.execute(stmt)
    issue = result.scalar_one_or_none()
    if not issue:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Issue '{issue_id}' not found.",
        )
    return issue


@router.post("/{issue_id}/triage", response_model=IssueResponse)
async def triage_issue(
    issue_id: str,
    payload: IssueTriageRequest,
    developer: DeveloperUser = Depends(require_developer_auth),
    db: AsyncSession = Depends(get_db),
):
    """
    Developer triage gate.
    Requires server-side authenticated developer. Explicitly accepts, rejects, requests info, or defers the issue.
    Actor is derived securely from authenticated developer identity.
    """
    actor_identity = developer.id or payload.actor or "developer"
    return await WorkflowEngine.triage_issue(
        db=db,
        issue_id=issue_id,
        decision=payload.decision,
        actor=actor_identity,
        notes=payload.notes,
    )


